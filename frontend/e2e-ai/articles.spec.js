import { test, expect } from '@playwright/test'
import { mkdir } from 'node:fs/promises'
async function shot(page,name) {
  await mkdir('../evidence/lab5/screenshots',{recursive:true})
  await page.screenshot({path:`../evidence/lab5/screenshots/${name}.png`, fullPage:true})
}
test('Thymeleaf form, HTTP Spring AI fixture, Record and clock',async({page})=>{
  await page.goto('/articles')
  await expect(page.getByText('ТЕСТОВИЙ РЕЖИМ.',{exact:true})).toBeVisible()
  await page.getByRole('button',{name:'Вставити приклад ↗'}).click()
  await shot(page,'01-input')
  await page.getByRole('button',{name:'Структурувати статтю'}).click()
  await expect(page.locator('#article-title')).toHaveText('Розвиток штучного інтелекту в економіці')
  await expect(page.locator('#pages')).toHaveText('11')
  await expect(page.locator('#language')).toHaveText('ukr')
  await expect(page.locator('#clock')).toHaveText(/\d+ мс · сервер/)
  await expect(page.locator('#fields tr')).toHaveCount(36)
  await shot(page,'02-result')
  await page.getByText('Переглянути JSON',{exact:true}).click()
  await expect(page.locator('#json')).toContainText('"total_volume_of_printed_sheets": "11"')
  await shot(page,'03-json')
  await page.getByRole('button',{name:'Очистити',exact:true}).click()
  await expect(page.locator('#message')).toHaveValue('')
  await expect(page.locator('#result')).toBeHidden()
})
test('Malformed provider JSON is shown as an error',async({page})=>{
  await page.goto('/articles')
  await page.getByLabel('Текст бібліографічного опису').fill('INVALID_JSON')
  await page.getByRole('button',{name:'Структурувати статтю'}).click()
  await expect(page.getByRole('alert')).toContainText('некоректну')
  await expect(page.locator('#submit')).toBeEnabled()
  await shot(page,'04-invalid-json')
})
test('Incomplete fixture becomes a null-safe 36-field Record',async({page})=>{
  await page.goto('/articles')
  await page.getByLabel('Текст бібліографічного опису').fill('INCOMPLETE: Partial citation')
  await page.getByRole('button',{name:'Структурувати статтю'}).click()
  await expect(page.locator('#article-title')).toHaveText('Partial citation')
  await expect(page.locator('#pages')).toHaveText('0')
  await expect(page.locator('#fields tr')).toHaveCount(36)
  await shot(page,'05-incomplete')
})
