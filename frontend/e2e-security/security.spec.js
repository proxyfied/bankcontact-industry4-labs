test('ADMIN tracks active users and logout removes the real servlet session', async ({ page, browser }) => {
  const userContext = await browser.newContext(), userPage = await userContext.newPage()
  await login(userPage, 'demo.user', 'UserDemo!2026')
  await login(page, 'demo.admin', 'AdminDemo!2026')
  expect((await page.goto('/admin')).status()).toBe(200)
  await expect(page.getByRole('cell', { name: 'demo.user', exact: true })).toBeVisible()
  await expect(page.getByRole('cell', { name: 'demo.admin', exact: true })).toBeVisible()
  await page.screenshot({ path: path.join(shots, '06-admin-sessions.png'), fullPage: true })
  await userPage.getByRole('button', { name: 'Вийти', exact: true }).click()
  await page.reload()
  await expect(page.getByRole('cell', { name: 'demo.user', exact: true })).toHaveCount(0)
  expect((await page.goto('/manager')).status()).toBe(403)
  await page.getByRole('button', { name: 'Вийти', exact: true }).click()
  await userContext.close()
})
test('second isolated browser context invalidates the first login', async ({ browser }) => {
  const a = await browser.newContext({ viewport: { width: 1440, height: 1050 } }), b = await browser.newContext({ viewport: { width: 1440, height: 1050 } })
  const first = await a.newPage(), second = await b.newPage()
  await login(first, 'demo.user', 'UserDemo!2026')
  expect((await first.goto(`${root}/user`)).status()).toBe(200)
  await login(second, 'DEMO.USER', 'UserDemo!2026')
  await first.goto(`${root}/user`)
  await expect(first).toHaveURL(/\/login\?expired$/)
  await expect(first.getByRole('alert')).toContainText('вхід з іншого браузера')
  await first.screenshot({ path: path.join(shots, '07-expired-first-browser.png'), fullPage: true })
  const active = await second.goto(`${root}/user`)
  expect(active.status()).toBe(200)
  await second.screenshot({ path: path.join(shots, '08-active-second-browser.png'), fullPage: true })
  await fs.writeFile(path.join(output, 'session-check.json'), JSON.stringify({ isolatedBrowserContexts: 2, sameCanonicalUsername: true, firstRedirect: '/login?expired', secondProtectedStatus: 200, secondLoginAccepted: true }, null, 2))
  await second.getByRole('button', { name: 'Вийти', exact: true }).click()
  await a.close(); await b.close()
})
test('CSRF is required and session cookies are HttpOnly and SameSite Lax', async ({ page, request }) => {
  const before = await request.post('/registration', { form: { username: 'csrf.attack', password: 'NeverCreated!2026', confirmation: 'NeverCreated!2026' } })
  expect(before.status()).toBe(403)
  expect((await request.post('/login', { form: { username: 'demo.user', password: 'UserDemo!2026' } })).status()).toBe(403)
  await login(page, 'demo.user', 'UserDemo!2026')
  const cookie = (await page.context().cookies()).find(c => c.name === 'BANKCONTACT_AUTH')
  expect(cookie.httpOnly).toBe(true); expect(cookie.sameSite).toBe('Lax')
  expect((await page.request.post('/logout')).status()).toBe(403)
  await expect(page.getByText('ROLE_USER', { exact: true })).toBeVisible()
  await page.getByRole('button', { name: 'Вийти', exact: true }).click()
  await fs.writeFile(path.join(output, 'csrf-cookie-check.json'), JSON.stringify({ registrationWithoutCsrf: 403, loginWithoutCsrf: 403, logoutWithoutCsrf: 403, cookieName: cookie.name, httpOnly: cookie.httpOnly, sameSite: cookie.sameSite }, null, 2))
})
