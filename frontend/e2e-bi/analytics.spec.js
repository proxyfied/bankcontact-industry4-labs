test('invalid workbook is rejected and template download is an actual xlsx', async ({ page, request }) => {
  await page.goto('/#/analytics')
  const download = page.waitForEvent('download')
  await page.getByRole('button', { name: 'Завантажити шаблон' }).click()
  const result = await download
  expect(result.suggestedFilename()).toBe('template.xlsx')
  const p = await result.path(), data = await fs.readFile(p)
  expect(data.subarray(0, 2).toString()).toBe('PK')
  await fs.writeFile(path.join(output, 'downloaded-template.xlsx'), data)
  await page.locator('#excel-file').setInputFiles({ name: 'broken.xlsx', mimeType: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet', buffer: Buffer.from('broken workbook') })
  await page.getByRole('button', { name: 'Імпортувати', exact: true }).click()
  await expect(page.getByRole('alert')).toContainText('Не вдалося прочитати Excel')
  expect((await (await request.get('http://localhost:8083/api/analytics')).json()).total).toBe(12)
})
test('network failure clears stale charts and retry restores the data', async ({ page }) => {
  await page.goto('/#/analytics'); await expect(page.getByTestId('bi-total')).toHaveText('12')
  await page.route('**/api/analytics', route => route.abort())
  await page.getByRole('button', { name: 'Оновити дані' }).click()
  await expect(page.getByRole('alert')).toContainText('Немає зв’язку з BI-сервісом')
  await expect(page.locator('canvas')).toHaveCount(0)
  await page.screenshot({ path: path.join(shots, '05-network-error.png'), fullPage: true })
  await page.unroute('**/api/analytics')
  await page.getByRole('button', { name: 'Повторити', exact: true }).click()
  await expect(page.getByTestId('bi-total')).toHaveText('12')
})
