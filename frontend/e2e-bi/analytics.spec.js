import { test, expect } from '@playwright/test'
import path from 'node:path'
import fs from 'node:fs/promises'
const output = path.resolve('../evidence/lab6'), shots = path.join(output, 'screenshots')
const file = path.resolve('../fixtures/lab6/template.xlsx')
test.beforeAll(async () => { await fs.mkdir(shots, { recursive: true }) })
test('Excel import updates real PostgreSQL statistics and both Chart.js canvases', async ({ page, request }) => {
  const errors = []; page.on('pageerror', error => errors.push(error.message))
  await page.goto('/#/analytics')
  await expect(page.getByTestId('bi-total')).toHaveText('0')
  await expect(page.getByText('Завантажте першу таблицю')).toBeVisible()
  await page.screenshot({ path: path.join(shots, '01-empty.png'), fullPage: true })
  await page.locator('#excel-file').setInputFiles(file)
  await page.screenshot({ path: path.join(shots, '02-selected.png'), fullPage: true })
  await page.getByRole('button', { name: 'Імпортувати', exact: true }).click()
  await expect(page.getByRole('status')).toContainText('Імпортовано: 12 записів')
  await expect(page.getByTestId('bi-total')).toHaveText('12')
  await expect(page.locator('canvas')).toHaveCount(2)
  await expect(page.getByText('66.7%', { exact: true })).toBeVisible()
  const res = await request.get('http://localhost:8083/api/analytics')
  expect(res.status()).toBe(200)
  const stats = await res.json()
  expect(stats.total).toBe(12); expect(stats.totalMinutes).toBe(114)
  expect(Object.fromEntries(stats.categories.map(b => [b.label, b.count]))).toEqual({ 'Картки': 3, 'Кредити': 3, 'Платежі': 3, 'Рахунки': 3 })
  expect(Object.fromEntries(stats.statuses.map(b => [b.label, b.count]))).toEqual({ CLOSED: 4, IN_PROGRESS: 2, NEW: 2, RESOLVED: 4 })
  expect(stats.dates.map(b => b.count)).toEqual([4, 4, 4])
  for(const canvas of await page.locator('canvas').all()) {
    const painted = await canvas.evaluate(c => {const a = c.getContext('2d').getImageData(0, 0, c.width, c.height).data; let count=0; for(let i=3;i<a.length;i+=4) if(a[i]) count++; return count})
    expect(painted).toBeGreaterThan(1000)
  }
  await fs.writeFile(path.join(output, 'analytics-response.json'), JSON.stringify(stats, null, 2))
  await page.screenshot({ path: path.join(shots, '03-import-success.png'), fullPage: true })
  await page.reload(); await expect(page.getByTestId('bi-total')).toHaveText('12')
  await page.getByRole('link', { name: 'Про проєкт', exact: true }).click()
  await page.getByRole('link', { name: 'BI аналітика', exact: true }).click()
  await expect(page.locator('canvas')).toHaveCount(2)
  expect(errors).toEqual([])
})
